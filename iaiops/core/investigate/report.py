"""The investigation as one self-contained HTML file — the thing you hand over.

HLD §13.9 orders the front ends: CLI **first**, this report **alongside it**, the
App page after, MCP last. The MCP front end got built first and this one — ordered
ahead of it — was skipped. `scan` and `oee measure` could both put their answer on
paper; the investigation, which is what an integrator actually hands to a plant,
could not.

**Where this deliberately parts company with the OEE report.** `oee measure
--report` *refuses* to write a file when the measurement was refused, and it is
right to: an OEE report is a number, so a file existing at all asserts that the
number was measured. An investigation report is the opposite. Its content is *how
far this got and what each remaining step needs* — so the blocked case is the one
most worth forwarding, and for a site nobody has instrumented yet it is the entire
deliverable.

What it must never do is let a blocked investigation LOOK finished. Hence the one
rule the section order encodes, the same rule the OEE report follows by putting
coverage before the number: **the headline is the walk, never a conclusion.** A
step's own words never appear above it.

The two-way distinction from §9.4 is carried all the way onto the page, because
losing it here would waste somebody's afternoon: a gap you have not supplied sends
a person to `config.yaml`, and a gap the product cannot accept sends them to the
issue tracker. Rendered identically, half of them go looking for a setting that
does not exist.

[PURE] No I/O, no clock. ``generated_at`` comes from the caller, so the same
payload renders the same bytes twice — two investigations of one incident have to
be diffable.
"""


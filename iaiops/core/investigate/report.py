def _strings(lang: str) -> dict:
    """Refuse an unknown language rather than falling back to English.

    A silent fallback is how a Chinese page ends up half English, and the strings
    added late are the honesty caveats — the ones that must not quietly vanish for
    half the readers.
    """
    key = (lang or "").strip().lower()
    if key not in LANGUAGES:
        raise ValueError(f"Unknown report language {lang!r}. Available: {', '.join(LANGUAGES)}.")
    return LANGUAGES[key]


def _header(t: dict, *, title: str, tiles: list[str], generated_at: str) -> str:
    cells = "".join(tiles + [kv(t["generated"], generated_at)])
    return "<h1>" + escape(title) + '</h1><dl class="kv grid">' + cells + "</dl>"


def _reach(t: dict, *, reached: int, total: int, tones: list[str], live: bool) -> str:
    """The walk, and nothing else. This is the only thing allowed above the steps.

    A renderer that promoted the last step's text here would read as a finding,
    and a blocked investigation would look finished.
    """
    if reached <= 0:
        sub = t["reach_none"]
    elif reached >= total:
        sub = t["reach_all"].format(total=total)
    else:
        sub = t["reach_live" if live else "reach_plan"].format(n=reached, total=total)
    boxes = "".join(
        '<li class="' + escape(tone) + '">' + str(i + 1) + "</li>"
        for i, tone in enumerate(tones[:total])
    )
    return (
        "<h2>" + escape(t["reach_h"]) + "</h2>"
        '<p class="reach">' + str(reached) + " / " + str(total) + "</p>"
        '<p class="reach-sub">' + escape(sub) + "</p>"
        '<ol class="strip">' + boxes + "</ol>"
    )


def _badge(state: str, tone: str) -> str:
    """The raw state rides in the class, so ``refused`` and ``not_possible`` stay
    two distinct words on the page rather than two shades of "not done"."""
    return (
        '<span class="badge '
        + escape(tone)
        + " "
        + escape(state)
        + '">'
        + escape(state)
        + "</span>"
    )


def _steps_table(t: dict, rows: str, third: str) -> str:
    return (
        "<h2>" + escape(t["steps_h"]) + "</h2>"
        '<div class="scroll"><table><thead><tr>'
        "<th>#</th><th>" + escape(t["step"]) + "</th><th>" + escape(t["state"]) + "</th>"
        "<th>" + escape(third) + "</th>"
        "</tr></thead><tbody>" + rows + "</tbody></table></div>"
    )


def _row(number: Any, label: str, badge: str, last: str) -> str:
    return (
        "<tr><td>" + escape(number) + "</td>"
        '<td class="wide">' + escape(label) + "</td>"
        "<td>" + badge + "</td>"
        '<td class="wide">' + escape(last) + "</td></tr>"
    )


def _plan_steps(t: dict, steps: list[dict]) -> str:
    rows = []
    for step in steps:
        status = str(step.get("status", ""))
        rows.append(
            _row(
                step.get("number", ""),
                str(step.get("label", "")),
                _badge(status, _PLAN_TONE.get(status, "none")),
                str(step.get("value", "")),
            )
        )
    return _steps_table(t, "".join(rows), t["gives"])


def _live_steps(t: dict, steps: list[dict]) -> str:
    rows = []
    for step in steps:
        state = str(step.get("state", ""))
        rows.append(
            _row(
                step.get("number", ""),
                str(step.get("label", "")),
                _badge(state, _LIVE_TONE.get(state, "none")),
                str(step.get("summary", "")),
            )
        )
    return _steps_table(t, "".join(rows), t["found"])


def _gap_key(req: dict) -> tuple[str, str]:
    """Group by the ACTION where there is one, since that is what a reader does.

    An inexpressible requirement has no fix by definition, so it groups by its own
    key — otherwise every inexpressible gap in a report would collapse into one.
    """
    fix = str(req.get("fix") or "").strip()
    if fix and not req.get("not_yet_expressible"):
        return ("fix", fix)
    return ("key", str(req.get("key") or req.get("label", "")))


def _gap_item(t: dict, steps_blocked: list, req: dict) -> str:
    label = escape(req.get("label", ""))
    detail = escape(req.get("detail", ""))
    where = ", ".join(escape(n) for n in steps_blocked)
    head = "<b>" + where + ". " + label + "</b>"
    if detail:
        head += " — " + detail
    if req.get("not_yet_expressible"):
        tail = '<span class="gap-fix gap-none">→ ' + escape(t["inexpressible"]) + "</span>"
    elif req.get("fix"):
        tail = '<span class="gap-fix">' + escape(t["fix"]) + ": " + escape(req["fix"]) + "</span>"
    else:
        tail = ""
    return "<li>" + head + tail + "</li>"


def _gaps(t: dict, steps: list[dict]) -> str:
    """Every unmet requirement ONCE, in walk order, saying which steps it holds up.

    Deduped by ACTION, not by requirement key. Deduping by key was the obvious
    move and it changed nothing: on a bare site four steps want four differently
    named things — "collected samples", "samples to check", "a sampled series",
    "evidence to rank" — that are all supplied by one `collect run`. Four keys,
    one action, four lines on a page whose own lead says it is ranked by where the
    walk stops. Four copies of one action read as four problems.

    Requirements with no fix (the inexpressible ones) fall back to their key, since
    they have no action to group by — by definition.

    The inexpressible marker is emitted HERE and nowhere else — not in a legend,
    not in the honesty section — so a report with no inexpressible gap does not
    carry the phrase at all. A marker that is always present marks nothing.
    """
    seen: dict[tuple[str, str], dict] = {}
    for step in steps:
        for req in step.get("requirements") or []:
            if req.get("met"):
                continue
            entry = seen.setdefault(_gap_key(req), {"req": req, "steps": []})
            if step.get("number", "") not in entry["steps"]:
                entry["steps"].append(step.get("number", ""))
    items = [_gap_item(t, e["steps"], e["req"]) for e in seen.values()]
    if not items:
        return (
            "<h2>" + escape(t["gaps_h"]) + "</h2>"
            '<p class="empty">' + escape(t["gaps_none"]) + "</p>"
        )
    return (
        "<h2>" + escape(t["gaps_h"]) + "</h2>"
        '<p class="sub">' + escape(t["gaps_lead"]) + "</p>"
        '<ul class="gaps">' + "".join(items) + "</ul>"
    )


def _not_claimed(t: dict) -> str:
    lines = "".join("<li>" + escape(x) + "</li>" for x in t["not_claimed"])
    return "<h2>" + escape(t["not_claimed_h"]) + '</h2><ul class="notes">' + lines + "</ul>"


def render_plan_report(payload: dict, *, lang: str = "en", generated_at: str = "") -> str:
    """[PURE] One self-contained file from ``iaiops investigate plan --json``.

    This is the report for a site that has not been instrumented yet: it says how
    far an investigation could get here and what each remaining step is waiting
    for. That it renders at all when nothing is reachable is the point — unlike
    the OEE report, the gaps are the deliverable.
    """
    t = _strings(lang)
    steps = list(payload.get("steps") or [])
    reached = int(payload.get("reachable_through", 0) or 0)
    tones = [_PLAN_TONE.get(str(s.get("status", "")), "none") for s in steps]
    body = "".join(
        [
            _header(
                t,
                title=t["plan_title"],
                tiles=[kv(t["site"], payload.get("site", ""))],
                generated_at=generated_at,
            ),
            _reach(
                t,
                reached=reached,
                total=int(payload.get("total_steps", len(steps)) or len(steps)),
                tones=tones,
                live=False,
            ),
            _plan_steps(t, steps),
            _gaps(t, steps),
            _not_claimed(t),
        ]
    )
    return document(
        title=f"{t['plan_title']} — {payload.get('site', '')}",
        body=body,
        footer=escape(t["footer"]),
        lang=lang,
        extra_css=_EXTRA_CSS,
    )


def render_live_report(payload: dict, *, lang: str = "en", generated_at: str = "") -> str:
    """[PURE] One self-contained file from ``iaiops investigate open/show --json``.

    The same eight steps over a real past window. A step that was not walked has
    no verdict here, and the page says so rather than leaving a blank that reads
    as "nothing was wrong".
    """
    t = _strings(lang)
    steps = list(payload.get("steps") or [])
    scope = payload.get("scope") or {}
    window = f"{scope.get('start', '')} → {scope.get('end', '')}"
    tones = [_LIVE_TONE.get(str(s.get("state", "")), "none") for s in steps]
    body = "".join(
        [
            _header(
                t,
                title=t["live_title"],
                tiles=[
                    kv(t["endpoint"], scope.get("endpoint", "")),
                    kv(t["asset"], scope.get("asset", "")),
                    kv(t["site"], payload.get("site", "")),
                    kv(t["window"], window),
                    kv(t["id"], payload.get("id", "")),
                    kv(t["opened"], payload.get("opened_at", "")),
                ],
                generated_at=generated_at,
            ),
            _reach(
                t,
                reached=int(payload.get("reached", 0) or 0),
                total=int(payload.get("total_steps", len(steps)) or len(steps)),
                tones=tones,
                live=True,
            ),
            _live_steps(t, steps),
            _not_claimed(t),
        ]
    )
    return document(
        title=f"{t['live_title']} — {scope.get('endpoint', '') or payload.get('site', '')}",
        body=body,
        footer=escape(t["footer"]),
        lang=lang,
        extra_css=_EXTRA_CSS,
    )



"""The point-list confirmation page — the App front end, as one static file.

HLD §13.9 orders the App page after the CLI and the report, and justifies it
narrowly: it exists for the steps where a person must go **row by row and tick**
— point-list confirmation, timeline review — where a table beats command-line
question-and-answer. It is not a dashboard.

**Why a file and not a served app.** A localhost server inside an OT box has to
answer which address it binds, who authenticates, and how the firewall is opened.
Worse, every declaration in this product requires ``--by``, and a page with no
identity cannot answer "who ticked this" — the one thing this step exists to
record. The file sidesteps all of it: it opens on the laptop already in the plant
office, and the CSV it produces goes through ``iaiops tags apply``, which is
where the author is supplied and where the refusals live.

**It re-implements no refusal.** ``run_state`` needing ``running_when``, a ref
having to be monitored, a role claimed twice — reproducing any of those in
JavaScript is how they drift from the ones that actually gate the config, and a
page that says "looks fine" while ``apply`` refuses is worse than no page. The
page collects; ``apply`` judges. The role options come from ``TagRole.ALL`` at
render time for the same reason: a hand-written list is how a fifth role appears
on a page and is then rejected with no explanation.

Unlike the investigation and OEE reports this page **does** ship script — it is a
form. What stays true is the property that matters in a plant: it makes **no
network request**, and its data is embedded, not fetched.

[PURE] No I/O, no clock. ``generated_at`` is the caller's.
"""


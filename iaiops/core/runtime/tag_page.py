# The page never decides anything, so the script only reads the controls and
# joins them into the same columns the CSV exporter uses. No rule lives here.
_JS = """
(function () {
  function quote(v) {
    var t = String(v == null ? '' : v);
    return /[",\\n]/.test(t) ? '"' + t.replace(/"/g, '""') + '"' : t;
  }
  function build() {
    var out = [SHEET.columns.join(',')];
    SHEET.rows.forEach(function (row, i) {
      var role = document.getElementById('role-' + i);
      var running = document.getElementById('run-' + i);
      // Driven by SHEET.columns rather than a hardcoded field order: pytest
      // never runs this script, so a reordering of SHEET_COLUMNS would have
      // shifted every value one column to the right with nothing to catch it.
      var live = { role: role ? role.value : '', running_when: running ? running.value : '' };
      out.push(SHEET.columns.map(function (name) {
        return quote(name in live ? live[name] : row[name]);
      }).join(','));
    });
    return out.join('\\n') + '\\n';
  }
  var area = document.getElementById('csv');
  function refresh() { if (area) { area.value = build(); } }
  document.addEventListener('change', refresh);
  document.addEventListener('input', refresh);
  refresh();
  var button = document.getElementById('download');
  if (button) {
    button.addEventListener('click', function () {
      var blob = new Blob([build()], { type: 'text/csv' });
      var link = document.createElement('a');
      link.href = URL.createObjectURL(blob);
      link.download = 'sheet.csv';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(link.href);
    });
  }
})();
"""


def _ref(tag: Any) -> str:
    value = getattr(tag, "ref", None)
    if value is None and isinstance(tag, dict):
        value = tag.get("ref")
    return str(value or "")


def _strings(lang: str) -> dict:
    key = (lang or "").strip().lower()
    if key not in LANGUAGES:
        raise ValueError(f"Unknown page language {lang!r}. Available: {', '.join(LANGUAGES)}.")
    return LANGUAGES[key]


def _embed(payload: dict) -> str:
    """Serialise for a ``<script>`` block.

    The escaping context here is JavaScript, not HTML text — a different trap
    from the reports. A tag label containing ``</script>`` would end the block
    early and turn everything after it into markup, so every ``<`` becomes
    ``\\u003c``: still valid JSON, still the same string once parsed, and no
    longer able to close the element.
    """
    return json.dumps(payload, ensure_ascii=False).replace("<", "\\u003c")


def _declared(row: dict[str, str], declared_running: dict[tuple[str, str], str]) -> str:
    """What config already says, as read-only context — role AND running_when.

    Both belong here rather than in the editable cells. Echoing the existing
    ``running_when`` into its input while leaving ``role`` blank was inconsistent
    in a way that bit: changing the role to a counter then got refused over a
    field the person never touched.
    """
    role = row["declared_role"]
    running = declared_running.get((row["endpoint"], row["ref"]), "")
    if role and running:
        return f"{role} (running_when: {running})"
    return role


def _row(
    t: dict,
    index: int,
    row: dict[str, str],
    roles: tuple[str, ...],
    declared_running: dict[tuple[str, str], str],
) -> str:
    options = "".join(f'<option value="{escape(role)}">{escape(role)}</option>' for role in roles)
    return (
        "<tr>"
        f"<td>{escape(row['endpoint'])}</td>"
        f'<td class="mono">{escape(row["ref"])}</td>'
        f"<td>{escape(row['label'])}</td>"
        f"<td>{escape(_declared(row, declared_running))}</td>"
        f'<td class="field"><select id="role-{index}">'
        f'<option value="">{escape(t["none"])}</option>{options}</select></td>'
        f'<td class="field"><input type="text" id="run-{index}" '
        f'value="" placeholder="{escape(t["running_hint"])}">'
        "</td>"
        "</tr>"
    )


def render_tag_page(config: Any, *, lang: str = "en", generated_at: str = "") -> str:
    """[PURE] One self-contained page for confirming what the point list means.

    Collects only. Everything it produces goes through ``iaiops tags apply``,
    which is where the refusals and the author live.
    """
    from iaiops.core.report.html import document
    from iaiops.core.runtime.config import TagRole

    t = _strings(lang)
    rows = sheet_rows(config)
    if not rows:
        body = (
            f"<h1>{escape(t['title'])}</h1>"
            f"<h2>{escape(t['empty_h'])}</h2>"
            f'<p class="empty">{escape(t["empty"])}</p>'
        )
        return document(
            title=t["title"],
            body=body,
            footer=escape(t["footer"]),
            lang=lang,
            extra_css=_EXTRA_CSS,
        )

    header = "".join(
        f"<th>{escape(t[key])}</th>"
        for key in ("endpoint", "ref", "label", "declared", "role", "running_when")
    )
    declared_running = {
        (str(getattr(target, "name", "")), _ref(tag)): " ".join(
            str(v) for v in (getattr(tag, "running_when", ()) or ())
        )
        for target in getattr(config, "targets", ()) or ()
        for tag in getattr(target, "tags", ()) or ()
    }
    table = "".join(
        _row(t, i, row, tuple(TagRole.ALL), declared_running) for i, row in enumerate(rows)
    )
    notes = "".join(f"<li>{escape(line)}</li>" for line in t["next"])
    payload = _embed(
        {
            "columns": list(SHEET_COLUMNS),
            "roles": list(TagRole.ALL),
            "rows": [dict(r) for r in rows],
        }
    )
    body = (
        f"<h1>{escape(t['title'])}</h1>"
        f'<p class="sub">{escape(t["lead"])} <span class="hint">{escape(generated_at)}</span></p>'
        f'<div class="scroll"><table><thead><tr>{header}</tr></thead>'
        f"<tbody>{table}</tbody></table></div>"
        f'<div class="actions"><button id="download" type="button">'
        f"{escape(t['download'])}</button>"
        f'<span class="hint">{escape(t["copy_h"])}</span></div>'
        '<textarea id="csv" readonly></textarea>'
        f'<h2>{escape(t["next_h"])}</h2><ul class="notes">{notes}</ul>'
    )
    return document(
        title=t["title"],
        body=body,
        footer=escape(t["footer"]),
        lang=lang,
        script=f"const SHEET = {payload};\n{_JS}",
        extra_css=_EXTRA_CSS,
    )
